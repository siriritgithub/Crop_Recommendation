def get_schemes(state, crop, include_private=True):
    """crop='All Crops' (or any crop not in the curated set) still returns
    the general/national schemes -- a farmer whose crop isn't listed always
    gets something useful rather than an empty result."""
    crop_key = crop.lower().strip() if crop != "All Crops" else None
    state_is_national = state in (None, "All States")

    schemes = list(GOVT_SCHEMES.get("All States", {}).get("All Crops", []))
    if not state_is_national:
        schemes += list(GOVT_SCHEMES.get(state, {}).get("All Crops", []))
    if crop_key:
        schemes += GOVT_SCHEMES.get("All States", {}).get(crop_key, [])
        if not state_is_national:
            schemes += GOVT_SCHEMES.get(state, {}).get(crop_key, [])

    if include_private:
        schemes += PRIVATE_SCHEMES.get("All States", {}).get("All Crops", [])
    return schemes

def get_crop_info(crop):
    return CROP_SEASONS.get(crop.lower(), {
        "season": "Varies by region",
        "reason": "Consult local agriculture department"
    })

def chatbot_answer(question):
    q = question.lower()
    for keyword, answer in CHATBOT_RESPONSES.items():
        if keyword in q:
            return answer
    return CHATBOT_RESPONSES["default"]
